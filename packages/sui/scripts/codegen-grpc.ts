/**
 * Generates TypeScript types for the sui-apis gRPC surface from the compiled
 * descriptor set, plus the descriptor set itself (base64) for the runtime
 * codec. No protobuf runtime is generated: `effect/protobuf` encodes and
 * decodes from descriptors; these types only describe the plain values.
 *
 *   bun run codegen   (protoc -> proto/sui-rpc.binpb -> src/grpc/generated/proto.ts)
 */
import { Result } from "effect"
import { ProtobufDescriptor, ProtobufMessage } from "effect/protobuf"

const bytes = await Bun.file(new URL("../proto/sui-rpc.binpb", import.meta.url)).bytes()
const registry = Result.getOrThrow(ProtobufDescriptor.fromFileDescriptorSet(bytes))

type Named = ProtobufDescriptor.MessageDescriptor | ProtobufDescriptor.EnumDescriptor

const all: Array<Named> = []
const visit = (m: ProtobufDescriptor.MessageDescriptor) => {
  all.push(m)
  m.enums.forEach((e) => all.push(e))
  m.messages.forEach(visit)
}
for (const f of registry.files) {
  f.enums.forEach((e) => all.push(e))
  f.messages.forEach(visit)
}

// Short TS names: nested types join with "_"; package prefix only on collision.
const local = (d: Named) => {
  const pkg = d.file.package
  return d.typeName.slice(pkg.length + 1).replace(/\./g, "_")
}
const counts = new Map<string, number>()
for (const d of all) counts.set(local(d), (counts.get(local(d)) ?? 0) + 1)
const RESERVED = new Set(["Object", "Function", "String", "Number", "Boolean", "Symbol", "Error", "Array", "Map", "Set", "Date", "Promise"])
const tsName = (d: Named) => {
  const l = local(d)
  const n = counts.get(l)! > 1 ? `${d.file.package.replace(/\./g, "_")}_${l}` : l
  return RESERVED.has(n) ? `${n}Message` : n
}

const scalarType = (s: ProtobufDescriptor.ScalarValueType) => {
  switch (s.scalar) {
    case "bool":
      return "boolean"
    case "string":
      return "string"
    case "bytes":
      return "Uint8Array"
    case "int64":
    case "uint64":
    case "fixed64":
    case "sfixed64":
    case "sint64":
      return s.jsType
    default:
      return "number"
  }
}

const valueType = (t: ProtobufDescriptor.ValueType): string =>
  t.kind === "scalar" ? scalarType(t) : t.kind === "enum" ? tsName(t.enum) : tsName(t.message)

const fieldType = (f: ProtobufDescriptor.FieldDescriptor): string =>
  f.kind === "list"
    ? `ReadonlyArray<${valueType(f.type)}>`
    : f.kind === "map"
    ? `Readonly<Record<string, ${valueType(f.type)}>>`
    : valueType(f.type)

const isRealOneof = (f: ProtobufDescriptor.FieldDescriptor) =>
  f.oneof !== undefined && f.proto.proto3_optional !== true

const doc = (s: string | undefined, indent = "") => (s ? `${indent}/** ${s} */\n` : "")

let out = `// Generated by scripts/codegen-grpc.ts from proto/sui-rpc.binpb (MystenLabs/sui-apis). Do not edit.
// Field names are the proto names, as effect/protobuf keys them. Every field is optional:
// absent on encode means "unset", and the domain layer decodes responses with Schema.
// Types only (plus enum value tables); descriptors and method handles live in rpc.ts.
/* eslint-disable */

`

for (const d of all) {
  const name = tsName(d)
  if (d._tag === "EnumDescriptor") {
    out += `${doc(d.typeName)}export const ${name} = {\n${d.values.map((v) => `  ${v.name}: ${v.number}`).join(",\n")}\n} as const\nexport type ${name} = (typeof ${name})[keyof typeof ${name}]\n\n`
    continue
  }
  const lines: Array<string> = []
  for (const f of d.fields) {
    if (isRealOneof(f)) continue
    lines.push(`  readonly ${f.name}?: ${fieldType(f)}`)
  }
  for (const o of d.oneofs) {
    const members = o.fields.filter(isRealOneof)
    if (members.length === 0) continue
    lines.push(
      `  readonly ${o.name}?:\n${members.map((f) => `    | { readonly _tag: "${f.name}"; readonly value: ${fieldType(f)} }`).join("\n")}`
    )
  }
  out += `${doc(d.typeName)}export interface ${name} {\n${lines.join("\n")}\n}\n\n`
}

await Bun.write(new URL("../src/grpc/generated/proto.ts", import.meta.url), out)

// -----------------------------------------------------------------------------
// rpc.ts: one descriptor chunk per top-level message/enum, one handle per method.
// Handles reference only the chunks their request/response reach, so a bundler
// keeps exactly the descriptors of the RPCs a program calls, shared ones once.
// -----------------------------------------------------------------------------

const set = Result.getOrThrow(ProtobufMessage.decode(ProtobufDescriptor.FileDescriptorSet)(bytes)) as any

const strip = (v: any): any => {
  if (Array.isArray(v)) return v.map(strip)
  if (v instanceof Uint8Array || v === null || typeof v !== "object") return v
  const o: Record<string, unknown> = {}
  for (const [k, x] of Object.entries(v)) {
    if (k === "json_name" || k === "source_code_info") continue
    if (Array.isArray(x) && x.length === 0) continue
    o[k] = strip(x)
  }
  return o
}
const literal = (v: any): string =>
  JSON.stringify(v, (_, x) => (typeof x === "bigint" ? Number(x) : x))

const topLevelOf = (typeName: string, pkg: string) => typeName.slice(0, pkg.length + 1 + typeName.slice(pkg.length + 1).split(".")[0]!.length)
const chunkName = (fullName: string) => "d_" + fullName.replace(/\./g, "_")

let rpc = `// Generated by scripts/codegen-grpc.ts. Do not edit.
import { chunk, file, rpc } from "../Rpc.ts"
import type * as P from "./proto.ts"

`
const fileVar = new Map<string, string>()
set.file.forEach((f: any, i: number) => {
  const v = `f${i}`
  fileVar.set(f.name, v)
  rpc += `const ${v} = /* @__PURE__ */ file(${literal({ name: f.name, package: f.package, syntax: f.syntax, dependency: f.dependency ?? [] })})\n`
})
rpc += "\n"
for (const f of set.file) {
  for (const m of f.message_type ?? []) {
    rpc += `const ${chunkName(`${f.package}.${m.name}`)} = /* @__PURE__ */ chunk(${fileVar.get(f.name)}, "message", ${literal(strip(m))})\n`
  }
  for (const e of f.enum_type ?? []) {
    rpc += `const ${chunkName(`${f.package}.${e.name}`)} = /* @__PURE__ */ chunk(${fileVar.get(f.name)}, "enum", ${literal(strip(e))})\n`
  }
}
rpc += "\n"

const closure = (roots: Array<ProtobufDescriptor.MessageDescriptor>) => {
  const seen = new Set<string>()
  const add = (d: ProtobufDescriptor.MessageDescriptor | ProtobufDescriptor.EnumDescriptor) =>
    seen.add(topLevelOf(d.typeName, d.file.package))
  const visited = new Set<string>()
  const visit = (m: ProtobufDescriptor.MessageDescriptor) => {
    if (visited.has(m.typeName)) return
    visited.add(m.typeName)
    add(m)
    for (const f of m.fields) {
      if (f.type.kind === "message") visit(f.type.message)
      if (f.type.kind === "enum") add(f.type.enum)
    }
    m.messages.forEach(visit)
  }
  roots.forEach(visit)
  return [...seen].sort()
}

let methodCount = 0
for (const f of registry.files) {
  for (const s of f.services) {
    for (const m of s.methods) {
      methodCount++
      const deps = closure([m.input, m.output]).map(chunkName).join(", ")
      rpc += `/** \`${s.typeName}/${m.name}\` */\nexport const ${s.name}_${m.name} = /* @__PURE__ */ rpc<P.${tsName(m.input)}, P.${tsName(m.output)}, ${m.serverStreaming}>(\n  "${s.typeName}/${m.name}", "${m.input.typeName}", "${m.output.typeName}", ${m.serverStreaming},\n  () => [${deps}]\n)\n`
    }
  }
}

await Bun.write(new URL("../src/grpc/generated/rpc.ts", import.meta.url), rpc)
console.log(`generated ${all.length} types, ${methodCount} methods`)
